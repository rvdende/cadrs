def wedge_basic_with_integrated_lattice(
    L: float = 30.0,
    W: float = 20.0,
    H: float = 15.0,
    shell_thickness: float = 2.0,
    branch_thickness_min: float = 0.5,
    branch_thickness_max: float = 2.5,
    num_seed_points: int = 30,
    neighbor_count: int = 3,
    seed: int = 0
) -> "cq.Workplane":
    """
    Build a triangular wedge (in X–Z plane, extruded along +Y) with a hollow shell
    and an integrated Voronoi-style lattice infill. The lattice is generated by
    random seed points in the triangle, connecting each to its nearest neighbors,
    extruding those connections as rods, and trimming to the wedge volume.
    Parameters:
      L, W, H                 – length (X), width (Y), height (Z) of the wedge
      shell_thickness         – thickness of the outer shell
      branch_thickness_min/max – minimum and maximum rod thickness
      num_seed_points         – number of random interior seeds
      neighbor_count          – how many nearest neighbors to connect per seed
      seed                    – random seed for repeatability
    """
    import cadquery as cq, math, random

    # Validate inputs
    if L <= 0 or W <= 0 or H <= 0:
        raise ValueError("L, W, H must be positive")
    shell_thickness = float(shell_thickness)
    if shell_thickness <= 0 or shell_thickness >= min(L, H):
        raise ValueError("shell_thickness must be > 0 and < min(L, H)")
    branch_thickness_min = float(branch_thickness_min)
    branch_thickness_max = float(branch_thickness_max)
    if branch_thickness_min <= 0 or branch_thickness_max < branch_thickness_min:
        raise ValueError("branch_thickness_min must be > 0 and <= branch_thickness_max")
    num_seed_points = int(num_seed_points)
    if num_seed_points < 1:
        raise ValueError("num_seed_points must be >= 1")
    neighbor_count = int(neighbor_count)
    if neighbor_count < 1:
        raise ValueError("neighbor_count must be >= 1")
    random.seed(int(seed))

    # 1) Base wedge in XZ, extruded along Y
    wedge_base = (
        cq.Workplane("XZ")
          .polyline([(0.0, 0.0), (L, 0.0), (0.0, H)])
          .close()
          .extrude(W)
    )

    # 2) Hollow the wedge to create an outer shell
    shell = wedge_base.faces(">Y or <Y").shell(-shell_thickness)

    # 3) Generate random seed points in the triangular profile
    pts = []
    for _ in range(num_seed_points):
        u = random.random()
        v = random.random()
        if u + v > 1.0:
            u, v = 1.0 - u, 1.0 - v
        pts.append((u * L, v * H))
    # anchor at the three corners
    pts.extend([(0.0, 0.0), (L, 0.0), (0.0, H)])

    # 4) Build nearest-neighbor segment list
    segments = []
    npts = len(pts)
    for i, (x1, z1) in enumerate(pts):
        dlist = []
        for j in range(i + 1, npts):
            x2, z2 = pts[j]
            d2 = (x2 - x1) ** 2 + (z2 - z1) ** 2
            dlist.append((d2, j))
        dlist.sort(key=lambda t: t[0])
        for k in range(min(neighbor_count, len(dlist))):
            idx = dlist[k][1]
            segments.append(((x1, z1), pts[idx]))

    # 5) Prepare segment data and compute distance-based thickness
    seg_data = []
    # triangle centroid for thickness interpolation
    centroid_x = L / 3.0
    centroid_z = H / 3.0
    for (x1, z1), (x2, z2) in segments:
        dx, dz = x2 - x1, z2 - z1
        length = math.hypot(dx, dz)
        if length < 1e-6:
            continue
        mid_x = 0.5 * (x1 + x2)
        mid_z = 0.5 * (z1 + z2)
        dist_centroid = math.hypot(mid_x - centroid_x, mid_z - centroid_z)
        seg_data.append((x1, z1, x2, z2, length, mid_x, mid_z, dist_centroid))

    # 6) Build and trim rods, then union with shell
    if seg_data:
        max_dist = max(d[7] for d in seg_data)
        rods_compound = None
        for x1, z1, x2, z2, length, mid_x, mid_z, dist_c in seg_data:
            # interpolate thickness
            t = branch_thickness_min
            if max_dist > 1e-6:
                t = branch_thickness_min + (branch_thickness_max - branch_thickness_min) * (dist_c / max_dist)
            half_t = 0.5 * t
            angle = math.degrees(math.atan2(z2 - z1, x2 - x1))
            rod = (
                cq.Workplane("XZ")
                  .polyline([
                      (-length / 2.0,  half_t),
                      ( length / 2.0,  half_t),
                      ( length / 2.0, -half_t),
                      (-length / 2.0, -half_t),
                  ])
                  .close()
                  .extrude(W)
                  .rotate((0, 0, 0), (0, 1, 0), angle)
                  .translate((mid_x, 0.0, mid_z))
            )
            # trim to the interior of the wedge
            inside = rod.intersect(wedge_base)
            rods_compound = inside if rods_compound is None else rods_compound.union(inside)
        # fuse shell and interior rods
        result = shell.union(rods_compound, clean=True)
    else:
        result = shell

    return result
