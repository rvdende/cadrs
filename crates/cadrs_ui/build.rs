//! Rasterizes the [cadrs_icons](https://crates.io/crates/cadrs_icons) icons at build time.
//!
//! Each icon is rendered at several pixel sizes (so small icons stay crisp instead of being
//! downscaled at runtime) and stored as raw straight-alpha RGBA8 in `OUT_DIR`. The generated
//! `icons.rs` embeds them with `include_bytes!`, so icons need no runtime file IO or decoding and
//! are available on the very first frame. Other sizes (a UI scale, a high-DPI screen) are
//! rendered at runtime with the same code (`src/icon_raster.rs`).

use std::fmt::Write as _;
use std::path::PathBuf;

use cadrs_icons::{Icon, Palette};

// `source` is for the runtime only.
#[allow(dead_code)]
#[path = "src/icon_raster.rs"]
mod icon_raster;

/// Pixel sizes each icon is rasterized at.
const SIZES: [u32; 6] = [10, 12, 14, 16, 20, 24];

fn main() {
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-changed=src/icon_raster.rs");
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let icon_out = out_dir.join("icons");
    std::fs::create_dir_all(&icon_out).unwrap();

    let mut entries: Vec<(&str, Icon, f32)> =
        cadrs_icons::ALL.iter().map(|i| (i.name, *i, 1.0)).collect();
    for &(name, base, scale) in icon_raster::WEIGHTS {
        let icon = cadrs_icons::get(base)
            .unwrap_or_else(|| panic!("cadrs_icons has no {base:?} for {name:?}"));
        entries.push((name, icon, scale));
    }

    let mut images = String::new();
    let mut accents = String::new();
    let mut full_colour = String::new();
    for (name, icon, scale) in &entries {
        // The viewport manipulators are drawn larger.
        let big: &[u32] = if name.starts_with("manipulator-") {
            &[48]
        } else {
            &[]
        };
        for &size in SIZES.iter().chain(big) {
            let (base, accent) = icon_raster::layers(icon, *scale, size);
            images += &embed(&icon_out, name, size, "", &base);
            if let Some(accent) = accent {
                accents += &embed(&icon_out, name, size, "accent", &accent);
            }
        }
        if !icon.kind.is_tintable() {
            writeln!(full_colour, "    {name:?},").unwrap();
        }
    }

    let a = Palette::LIGHT.accent;
    let code = format!(
        "/// Generated by build.rs: (name, pixel size, straight-alpha RGBA8 pixels).\n\
         pub static ICON_DATA: &[(&str, u32, &[u8])] = &[\n{images}];\n\
         /// Accent layers of tintable icons, in white: (name, pixel size, pixels).\n\
         pub static ACCENT_DATA: &[(&str, u32, &[u8])] = &[\n{accents}];\n\
         /// Icons drawn in their own colours, which are faded but never tinted.\n\
         pub static FULL_COLOUR: &[&str] = &[\n{full_colour}];\n\
         /// cadrs_icons's accent colour, for the accent layers.\n\
         pub const ACCENT: [u8; 3] = [{}, {}, {}];\n",
        a.0, a.1, a.2
    );
    std::fs::write(out_dir.join("icons.rs"), code).unwrap();
}

/// Writes one raster and returns its `ICON_DATA` / `ACCENT_DATA` row.
fn embed(dir: &std::path::Path, name: &str, size: u32, layer: &str, svg: &str) -> String {
    let file = format!(
        "{name}_{size}{}{layer}.rgba",
        if layer.is_empty() { "" } else { "_" }
    );
    let pixels = icon_raster::rasterize(svg, size)
        .unwrap_or_else(|e| panic!("rasterizing icon {name}: {e}"));
    std::fs::write(dir.join(&file), pixels).unwrap();
    format!(
        "    ({name:?}, {size}, include_bytes!(concat!(env!(\"OUT_DIR\"), \"/icons/{file}\"))),\n"
    )
}
